function pgfabric2(tf1x, tf1y, tf1w, tf1h) {
  tf1y=tf1y-h[30];
  tsm = 0.8;
  tsm2 = 0.4;
  tzf = 0.001;
  tzf2 = 0.001;
  tfr = 0;
  noiseSeed(myRandom(0, 1000));
  pg.noFill();
  pg.noStroke();
  pg.fill(255);
  let trows = tf1h + tf1y;
  let tcolumns = tf1w + tf1x;
    for (let j = tf1y; j < trows; j += e[20]) {
    tfc = 0;
    twave1[j] = [];
    twave2[j] = [];
    for (let ta = 0; ta < PI * 2; ta += PI / 640) {
      let txf = pg.map(cos(ta), -1, 1, 0, tsm);
      let tyf = pg.map(sin(ta), -1, 1, 0, tsm);
      let txf2 = pg.map(cos(ta), -1, 1, 0, tsm2);
      let tyf2 = pg.map(sin(ta), -1, 1, 0, tsm2);
      tr = pg.map(noise(txf, tyf, tzf), 0, 1, e[0], e[210]);
      tr2 = pg.map(noise(tyf2, txf2, tzf2), 0, 1, e[0], e[100]);
      twave2[j].push(tr2);
      twave1[j].push(tr);
      tsm += 0.00001;
      tsm2 += 0.000007;
      
    }
    tzf += 0.00001;
    for (let i = tf1x; i < tcolumns; i += e[20]) {
      if (tfr < 1) pgtfraytop(i + twave2[j][tcount], j + twave1[j][tcount]);
      if (tfc < 1) pgtfrayleft(i + twave2[j][tcount], j + twave1[j][tcount]);
      pgtweave(i + twave2[j][tcount], j + twave1[j][tcount],tf1w,tf1h);
      if (rcount==0){pg.fill(features.fab2vert);pg.rect(i + e[100], j + e[210],tf1w-e[60],tf1h-e[160]);}
      tcount += 1;rcount+=1;
      
      if (j > tf1y + tf1h - e[20])pgtfraybottom(i + twave2[j][tcount], j + twave1[j][tcount] + e[16]);
      tfc = 1;
      tcount += 1;
    }
    pgtfrayright(tf1x + tf1w + twave2[j][tcount], j + twave1[j][tcount]);
    tfr = 1;
    tcount = 0;
  }
}
