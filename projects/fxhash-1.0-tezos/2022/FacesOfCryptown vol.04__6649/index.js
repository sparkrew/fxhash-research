const getFileDigits = (name) => {
  return name.split('_')[1].split('.')[0]
}

const config = {
  Background: getBackground(Math.random()),
  Head: getHead(Math.random()),
  Mouth: getMouth(Math.random()),
  RightEye: getRightEye(Math.random()),
  LeftEye: getLeftEye(Math.random()),
}

window.$fxhashFeatures = {
 
  Head: getFileDigits(config.Head),
  Mouth: getFileDigits(config.Mouth),
  RightEye: getFileDigits(config.RightEye),
  LeftEye: getFileDigits(config.LeftEye),
}

const allImages = Object.entries(config).map((entrie) => entrie[1])
allImages.forEach((image) => {
  const $wrapp = document.createElement('div')
  const $image = document.createElement('img')
  $wrapp.classList.add('image')
  $image.setAttribute('src', image)
  $wrapp.append($image)
  document.body.append($wrapp)
})
