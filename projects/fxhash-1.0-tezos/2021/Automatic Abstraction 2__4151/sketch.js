class figureframe {

  
  constructor(cColor, x, y) {
    this.color = cColor;
    this.x = x;
    this.y = y;
    this.speed = 0;
  }

  start(speed) { 
    this.speed = speed;
  }

  display() { // method!
    
    fill(this.color);
    stroke(this.color);
    rect(this.x, this.y, (10*fxrand()/fxrand()), ((100*fxrand())/fxrand()));

  }
  
    
  move() { // method!
    this.y += this.speed;
    // Wrap x around boundaries
    if (this.y < -1000) {
      this.y = width;
    } else if (this.y > width) {
      this.y = -1000;
    }
  }
} //end class figureframe

