class noisePoint{
	 
	 
	 constructor(_x,_y,_c1,_c2){
		 
		this.x = _x;
		this.y = _y;
		
		
		this.seed = genR(1000000);
		

		let b = 30;		
		
		
		if(uniforms_fxhash.palette == 0){
			this.c = color(genR(100,200)+b,genR(100,200)+b,genR(100,200)+b);
			this.c2 = color(genR(100,200)+b,genR(100,200)+b,genR(100,200)+b);
		}else if(uniforms_fxhash.palette == 1){
			this.c = color(255);
			this.c2 = color(255);
		}else if(uniforms_fxhash.palette == 2){
		
			//this.c = color(genR(150,255)+b,genR(0,220)+b,genR(100,200)+b);
			//this.c2 = color(genR(100,200)+b,genR(0,200)+b,genR(150,255)+b);
			
			//this.c = color(genR(0,255),genR(0,255),genR(0,255));
			//this.c2 = color(genR(0,255),genR(0,255),genR(0,255));
			
			//this.c = color(genR(0,255),genR(0,100),genR(0,100));
			//this.c2 = color(genR(0,150),genR(0,100),genR(200,255));
			
			/*let ama = genR(100,255);
			
			colorMode(HSB);
			//this.c = color(ama,ama,100);
			//this.c2 = color(ama,ama,100);
			
			
			let rdm = 25;
		  
			this.c = color(uniforms_fxhash.singlecolor+ genR(-rdm,rdm),genR(150,200),genR(100,255));
			this.c2 = color(uniforms_fxhash.singlecolor+ genR(-rdm,rdm),genR(150,200),genR(100,255));
			colorMode(RGB);*/
			let palet;
			
			if(genR(1) < 0.5){
				palet = getFromPalette(0);
			}else{
				palet = getFromPalette(2);
			}
			this.c = palet.c1;
			this.c2 = palet.c2;
		}
	
		this.life = 1;
	 
		//EL QUE VA 
		this.mins = genR(0,10);
		//this.mins = 0;
		this.maxs = genR(2,10);
		
		//EL DE PRUEBA : 
		//this.mins = 100;
		//this.maxs = 300;
		
		
		this.shadows = 1.5;
		this.cnt2 = floor(genR(20,30));
		
		this.ampx = uniforms_fxhash.maxamp;
		this.xspeed = genR(0.0,2.0);
		
		/*if(genR(1) < 0.2){
			this.maxshadows = genR(2,8);	
		}else{
			this.maxshadows = genR(1,4);	
		}*/
		
		
		this.maxshadows = genR(1.3,3.5);
		this.minshadows = genR(1);
		this.lifeindex = 0;
		this.palette = 2;
	 }
	 
	 display(_ps){
		 
		 
		
		 
		 
		
		//let lifeindex = 0.0;
		
		let num = 10;
		if(this.life < 0.3){
			this.life-=genR(0.001,0.001);
		}else{			
			this.life-=genR(0.004,0.008);
			
		}
		//this.life-=pow(this.life,uniforms_fxhash.rlife)*0.005;
		/*if(this.life < 0.3){
			this.lifeindex+= this.life*num*8.;
		}else{
			this.lifeindex+= this.life*num*.5;
		}*/
		
		this.lifeindex+=pow(2, this.life)*uniforms_fxhash.noiseforce;
		
		   	
		let xf = this.x+sin(this.lifeindex*0.04+this.seed*1000.)*map(this.life,1.0,0.0,this.ampx,this.ampx*0.5);
		let yf = this.y+map(noise(this.lifeindex*0.006+this.seed*15000),0,1,-height,height);
		
		//if(this.life < 0.1){
			//yf = lerp(yf,height/2,0.5);
		//}
			
			
			
		let s = noise(this.lifeindex*0.006+4020*this.seed)*500*map(this.life,1,0,1,0.0);
			s = noise(this.lifeindex*0.01+40202*this.seed)*500*map(this.life,1,0,1,0.0);
			//s = map(s,1,0,this.mins,this.maxs)*this.life;

		let b = noise(millis()*0.001+this.seed*1000.)*255;
		let cindex = sin(this.life*TWO_PI*2.+this.seed*500.)*.4+.6
			//cindex = sin(this.lifeindex*TWO_PI*0.01+this.seed*500.)*.4+.6
		
		
		this.life = constrain(this.life,0.0,1.0);
		
		let a = map(this.life,1,0,0,TWO_PI);
		let cf2 = lerpColor(this.c,this.c2,this.life);
		let cf = lerpColor(cf2,color(0),cindex);
		
			if(uniforms_fxhash.tpalette == 0){
				cf = lerpColor(this.c,color(0),genR(1));
			}else if(uniforms_fxhash.tpalette == 1){
				cf = lerpColor(cf2,color(0),cindex);
			}
			/*}else if (uniforms_fxhash.palette == 2){
				cf = lerpColor(color(255),color(0),genR(1));
			}*/
			
		for(let k=0; k<this.cnt2; k++){
			let ss = map(k,0,this.cnt2-1,this.shadows*(s+this.maxs)*this.maxshadows,(s+this.mins)*this.minshadows);
				ss = map(k,0,this.cnt2-1,(s+this.maxs)*this.maxshadows,(s+this.mins)*this.minshadows);
			let alf = map(k,0,this.cnt2-1,0,255);
			
		
				if(k == this.cnt2-1){
					cf.setAlpha(alf);
					_ps.fill(cf);		
				}else{
					if(uniforms_fxhash.noshadow == 2){
						cf.setAlpha(genR(100,255));
					}else{
						cf.setAlpha(5);
						
					}
					_ps.fill(cf);
				}
			
			if(this.life>0){
				if(uniforms_fxhash.specialform == 0){
				_ps.ellipse(xf,yf,ss,ss);
				}
				else{
					_ps.push();
					_ps.translate(xf,yf);
					_ps.rotate(a*4+this.seed);
					_ps.rectMode(CENTER);
					_ps.rect(0,0,ss,ss);
					_ps.pop();
				}
			}
		}
		//_ps.fill(this.c);
		//_ps.ellipse(this.x,this.y,80,80);
	 }
}