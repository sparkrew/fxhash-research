let m, nf;
let w = 2000;

function setup() {
  preDraw();
  noLoop();
  palC = floor(random(32));
  PalName = palNames[palC];
  bg = random(1);
  if (bg < 0.4) {
    bgC = "snow";
  } else if (bg < 0.8) {
    bgC = "antiquewhite";
  } else if (bg < 0.91) {
    bgC = random(pal[palC]);
  } else {
    bgC = "#191917";
  }

  m = w / 40;
  nf = random(0.002, 0.2);
  xspac = (width - 2 * m) / random([10, 20, 40]);
  yspac = (height - 2 * m) / random([10, 20, 40]);
  shape = random();
  scx = random();
  ww = width / 2;
  hh = height / 2;
  mode = random();
  jaws = random();
  mess = random();
  imageMode(CENTER);
  gralis = 1;

  main = createGraphics(width, height);
  main.blendMode(MULTIPLY);

  ranger = random();
  if (ranger < 0.6) {
    range = 10;
  } else if (ranger < 0.85) {
    range = 15;
  } else {
    range = 42;
  }

  lin = random();
  if (lin < 0.9) {
    stW = 5;
  } else if (lin < 0.95) {
    stW = 2;
  } else {
    stW = 11;
  }

  tex = random();

  //FEATURES
  window.$fxhashFeatures = {
    Palette: PalName,
    Style: getFeatureString("Style", mode),
    Jaws: getFeatureString("Jaws", jaws),
    Mirror: getFeatureString("Mirror", scx),
    Range: getFeatureString("Range", ranger),
    Tex: getFeatureString("Tex", tex),
    Lines: getFeatureString("Lines", lin),
    Smoodge: getFeatureString("Smoodge", mess),
    "g r a l i s": getFeatureString("gralis", gralis),
  };
}

function getFeatureString(feature, value, value2) {
  if (feature == "Style") {
    if (value < 0.5) return "Horizontal";
    else return "Vertical";
  }
  if (feature == "Jaws") {
    if (value < 0.5) return "No";
    else return "Yiis";
  }
  if (feature == "Mirror") {
    if (value < 0.5) return "No";
    else return "Yiis";
  }
  if (feature == "Range") {
    if (value < 0.6) return "Normal";
    if (value < 0.85) return "Extended";
    else return "42";
  }
  if (feature == "Lines") {
    if (value < 0.9) return "Normal";
    if (value < 0.95) return "Fine";
    else return "Thicc";
  }
  if (feature == "Smoodge") {
    if (value < 0.02) return "Smoodged";
    else return "No Smoodge for you";
  }
  if (feature == "Tex") {
    if (value < 0.31) return "Edge";
    else return "Curvy";
  }

  if (feature == "gralis") {
    if (value > 0) return "g r a l i s";
  }
}

function draw() {
  background(bgC);
  main.strokeCap(SQUARE);

  if (mode < 0.5) {
    horizontal();
  } else {
    vertical();
  }

  ///Texture
  if (mess < 0.02) {
    filter(BLUR, random(2, 11));
    filter(POSTERIZE, random(4.2, 11));
  }

  noiseImage(this, 1, 11); //texture overlay2

  fxpreview();
}

function vertical() {
  main.noFill();
  // main.stroke("#19191742")
  main.strokeWeight(stW);

  for (let i = 0; i < 150; i++) {
    c = color(random(pal[palC]));
    cc = color(hue(c), saturation(c), brightness(c) - 0.001 * i, 0.042 * i);
    main.stroke(cc);

    main.beginShape();
    for (let y = m; y <= height - m; y += yspac) {
      let n = noise(ww * nf, y * nf);
      let x = width - 2 * m - (n * range * i) / 2;
      if (tex < 0.31) {
        main.vertex(x, y);
      } else {
        main.curveVertex(x, y);
      }
    }
    main.endShape();
  }

  if (jaws < 0.5) {
    push();
    image(main, m * 2, hh);
    pop();

    if (scx < 0.5) {
      push();
      translate(width - m * 2, hh);
      scale(-1, -1);
      image(main, 0, 0);
      pop();
    } else {
      push();
      translate(width - 2 * m, hh);
      scale(-1, 1);
      image(main, 0, 0);
      pop();
    }
  } else {
    push();
    image(main, ww, hh);
    pop();

    if (scx < 0.5) {
      push();
      translate(ww, hh);
      scale(-1, -1);
      image(main, 0, 0);
      pop();
    } else {
      push();
      translate(ww, hh);
      scale(-1, 1);
      image(main, 0, 0);
      pop();
    }
  }
}

function horizontal() {
  main.noFill();
  main.strokeWeight(stW);

  for (let i = 0; i < 150; i++) {
    c = color(random(pal[palC]));
    cc = color(hue(c), saturation(c), brightness(c) - 0.001 * i, 0.042 * i);
    main.stroke(cc);

    main.beginShape();
    for (let x = m; x <= width - m; x += xspac) {
      let n = noise(x * nf, hh * nf);
      let y = height - 2 * m - (n * range * i) / 2;
      if (tex < 0.31) {
        main.vertex(x, y);
      } else {
        main.curveVertex(x, y);
      }
    }
    main.endShape();
  }

  if (jaws < 0.5) {
    push();
    image(main, ww, m * 2);

    pop();

    if (scx < 0.5) {
      push();
      translate(ww, height - m * 2);
      scale(-1, -1);
      image(main, 0, 0);
      pop();
    } else {
      push();
      translate(ww, height - m * 2);
      scale(1, -1);
      image(main, 0, 0);
      pop();
    }
  } else {
    push();
    image(main, ww, hh * 0.9);

    pop();

    if (scx < 0.5) {
      push();
      translate(ww, hh * 1.1);
      scale(-1, -1);
      image(main, 0, 0);
      pop();
    } else {
      push();
      translate(ww, hh * 1.1);
      scale(1, -1);
      image(main, 0, 0);
      pop();
    }
  }
}

function noiseImage(img, scaleFactor, amount) {
  img.loadPixels();
  let change = amount * sqrt(scaleFactor);
  let size =
    4 * (img.width * img.pixelDensity()) * (img.height * img.pixelDensity());
  let pixels = img.pixels;
  for (let i = 0; i < size; i += 4) {
    var n = -change + random() * change * 2;
    pixels[i] += n;
    pixels[i + 1] += n;
    pixels[i + 2] += n;
  }
  img.updatePixels();
}

function preDraw() {
  let seed = floor(999999 * fxrand());
  randomSeed(seed);
  noiseSeed(seed);
  let tempcan = createCanvas(w * 0.75, w);
  tempcan.parent("fulllscreen");
  rectMode(CENTER);
  pixelDensity(2);
  colorMode(HSL);
}

