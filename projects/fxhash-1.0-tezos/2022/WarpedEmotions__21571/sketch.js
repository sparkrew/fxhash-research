function setup(){
  preDraw();
  
  palC = floor(random(29)); 
  PalName = palNames[palC];
  bgC = random(["snow", pal[palC][0],"#010101",pal[palC][4]]);
  m = random([w/12,w/10,w/20,w/12]);
  fR = random([25,42,60]);
  frameRate(fR);
  
  g = createGraphics(wC*0.75, wC);
  g.imageMode(CENTER);
  g.rectMode(CENTER);
  g.colorMode(HSL);
  g.blendMode(MULTIPLY);

  k = createGraphics(wC*0.75, wC);
  k.imageMode(CENTER);
  k.rectMode(CENTER);

  main = createGraphics(width, height);
  main.imageMode(CENTER);
  main.rectMode(CENTER);
  main.colorMode(HSB);
  
  z = createGraphics(width, height);
  z.rectMode(CENTER);
  
  b1 = color(hue(bgC),saturation(bgC)-5,brightness(bgC)+10,1)
  background(bgC);
  imageMode(CENTER);
  
  noiseLevel = random();
  if (noiseLevel < 0.91) {
    noisefx = random(0.002, 0.0042);
    noisefy = random(0.002, 0.0042);
  } else {
    noisefx = random(0.004, 0.0088);
    noisefy = random(0.004, 0.0088);
  }

  nf = random(0.002, 0.008);
  
  size = 420;
  constrict = random();
  frames = round(random(69, 111));
  mainRot = random();
  shift = random([20, 42, 69]);
  shift1 = shift*2;
  fract = random();
  fracShape = random();
  uD = random();
  rot = random(TAU);
  rot1 = rot;
  rotated = random();
  ww = width / 2;
  hh = height / 2;
  w1 = wC*0.75/2;
  h1 = wC/2;
  dep = random([0.3, 0.4, 0.5, 0.6, 0.75]);
  a=1;
  spacing = random([5,10]);
  inc = random([0.5,1,1.5,1])
  gralis = 1;
  birthday = round(random(1,365));
  
  if (fract<0.2){
  ifs(0,0,width,height,0);
  }
  
  splash();
  for (let i = 0; i < frames; i++) {
    if (mainRot < 0.8) {
      k.push();
      k.translate(w1, h1);
      k.rotate(random([0, PI]));
      k.image(g, 0, 0);
      k.pop();
    } else {
      k.push();
      k.translate(w1, h1);
      k.rotate(HALF_PI);
      k.image(g, 0, 0, height, width);
      k.pop();
    }

    h1 += random(-shift, shift);
    w1 += random(-shift, shift);
  }
  
  t=0;
  f=0;
  
  
  //FEATURES
  window.$fxhashFeatures = {
    Palette: PalName,
    Fracture: getFeatureString("Fracture", fract),
    Spacing: spacing,
    Frantic: getFeatureString("Frantic", noiseLevel),
    "g r a l i s": getFeatureString("gralis", gralis),
    BirthdayPunches: birthday,
  };
  
}

function getFeatureString(feature, value) {
  if (feature == "Fracture") {
    if (value < 0.2) return "Yes";
    else return "No";
  }
  if (feature == "Frantic") {
    if (value < 0.69) return "Less";
    else return "More";
  }
  if (feature == "gralis") {
    if (value > 0) return "g r a l i s";
  }
}

function preDraw(){
  let seed = floor(999999 * fxrand());
  randomSeed(seed);
  noiseSeed(seed);
  let tempcan = createCanvas(w * 0.75, w);
  tempcan.parent("fulllscreen");
  rectMode(CENTER);
  pixelDensity(2);
  colorMode(HSB);
}

function draw(){
  main.background(bgC);

  push();
  translate(ww, hh);
  image(k, 0, 0,width,height);
  pop();

  main.stroke(bgC);
  main.fill(bgC);
 
  for (let tx = m; tx <= width - m; tx += spacing) {
    for (let ty = m; ty < height - m; ty += spacing) {
      
      n1 = noise(tx * noisefx, ty * noisefx);
      n2 = noise(tx * noisefy, ty * noisefy);
      n3 = noise((tx + offset * n1) * noisefx, (ty + offset * n2) * noisefy, f);
      n4 = noise(
        (tx + offset * n3) * noisefx,
        (ty + t + offset * n3) * noisefy,
        f
      );
      n = noise(
        (tx + offset * n4) * noisefx,
        (ty + t + offset * n4) * noisefy,
        f
      );

  
      let nn = round(n * 10);
      let nn1 = round(n4 * 10);
      
      if (uD <0.5){

      if (nn < nn1) {
        main.erase();
        main.square(tx,ty, spacing);
        
        main.noErase();
      }
      } else {
      
      if (nn > nn1) {
        main.erase();
        
        main.square(tx, ty, spacing);
        
        main.noErase();
      }  
        
      }  
      ////  
      
    }
  }

  t += noisefx*inc;
  f += noisefy*inc;
 

  push();
  translate(ww, hh);
  image(main, 0, 0);
  pop();
  
  if (fract<0.2){
  image(z,ww,hh);
  }
  

  if (frameCount === 1){
    fxpreview()
  }
}

function draw_box(x, y, d_x, d_y) {
  offset = random(abun);
  n1 = noise(x * noisefx, y * noisefx);
  n2 = noise(x * noisefy, y * noisefy);
  n3 = noise((x + offset * n1) * noisefx, (y + offset * n2) * noisefy, f);
  n4 = noise((x + offset * n3) * noisefx, (y + t + offset * n3) * noisefy, f);
  n = noise((x + offset * n4) * noisefx, (y + t + offset * n4) * noisefy, f);

  z.noStroke();
  z.fill(bgC);

  if (rotated<0.91){
  let rr = random();
  if (rr < 0.34) {
    if (fracShape<0.95){
    z.push();
    z.translate(x + d_x / 2, y + d_y / 2);
    z.rect(0, 0, d_x, d_y);
    z.pop();
    } else {
    z.push();
    z.translate(x + d_x / 2, y + d_y / 2);
    z.circle(0, 0, min(d_x,d_y));
    z.pop();  
    }  
  }
    
  } else {
   
   let rr = random();
  if (rr < 0.34) {
    z.push();
    z.translate(x + d_x / 2, y + d_y / 2);
    z.rotate(n*rot);
    z.rect(0, 0, d_x, d_y);
    z.pop();
  } 
  }  

  t += 0.0042;
  f += 0.00042;
}

function ifs(x, y, d_x, d_y, depth) {
  const a = random(0.1, 1);

  if ((a < 0.1) | (depth > 3)) {
    draw_box(x, y, d_x, d_y);
    return;
  }
  const n_x = floor(random(1, 3));
  const n_y = floor(random(1, 3));
  const new_d_x = d_x / n_x;
  const new_d_y = d_y / n_y;

  for (let x_i = 0; x_i < n_x; x_i++) {
    for (let y_i = 0; y_i < n_y; y_i++) {
      ifs(x + x_i * new_d_x, y + y_i * new_d_y, new_d_x, new_d_y, depth + dep);
    }
  }
}

function splash() {
  sNum = 12000;
  offset = random(abun) * 11;
  for (let i = 0; i < sNum; i++) {
    let r = random(11, size);
    if (constrict < 0.02) {
      x = random(m + r, wC*0.75 - m - r);
      y = random(m / 2 + r, wC - m / 2 - r);
    } else {
      x = random(m, wC*0.75 - m);
      y = random(m, wC - m);
    }

    n1 = noise(x * noisefx, y * noisefx);
    n2 = noise(x * noisefy, y * noisefy);
    n3 = noise((x + offset * n1) * noisefx, (y + offset * n2) * noisefy, f);
    n4 = noise((x + offset * n3) * noisefx, (y + t + offset * n3) * noisefy, f);
    n5 = noise((x + offset * n4) * noisefx, (y + t + offset * n4) * noisefy, f);
    n = noise((x + offset * n5) * noisefx, (y + t + offset * n5) * noisefy, f);


    p = round(n*pal[palC].length)
    let c = color(pal[palC][p]);
    let nC = color(hue(c), saturation(c), brightness(c), n * 0.005);
    let wT = color(hue(bgC), saturation(bgC), brightness(bgC), n * 0.004);
    if (random() < 0.1) {
      g.stroke(wT);
    } else {
      g.noStroke();
    }
    g.fill(nC);

    g.push();
    g.translate(x, y);
    g.rotate(n * rot);
    if (random() < 0.69) {
      g.circle(0, 0, n4 * r, n5 * r);
    } else {
      g.rect(0, 0, n4 * r, n5 * r);
    }
    g.pop();

    t += 0.00042;
    f += 0.00069;
  }
}

function noiseImage(img, scaleFactor, amount) {
  img.loadPixels();
  let change = amount * sqrt(scaleFactor);
  let size =
    4 * (img.width * img.pixelDensity()) * (img.height * img.pixelDensity());
  let pixels = img.pixels;
  for (let i = 0; i < size; i += 4) {
    var n = -change + random() * change * 2;
    pixels[i] += n;
    pixels[i + 1] += n;
    pixels[i + 2] += n;
  }
  img.updatePixels();
}

function keyTyped() {
  if (key === "s" || key === "S") {
    noiseImage(this, 1, 11);
    saveCanvas("WarpedEmotions", "png");
  }
  if (key === "q" || key === "Q") {
    noLoop(); //pause
  }
  if (key === "w" || key === "W") {
    loop(); //resume
  }
  
  if (key === "m" || key === "M") {
    setup(); //restart
  }
  
}
