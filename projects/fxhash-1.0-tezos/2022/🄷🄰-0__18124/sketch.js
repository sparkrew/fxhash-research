let m, nf;

let w = 2000;
function setup() {
  preDraw();
  palC = floor(random(37));
  if (random(1)<0.95){
  bgC = random([random(pal[palC]), "#f1f1f1", "#f1f1f1"]);
  } else {
    bgC = "#191917";
  }  
  m = width / 5;
  gap = random([25, 50, 100]);
  nf = random(0.002, 0.2);
  num = floor(random(4, 12));

  xspac = (width - 2 * m - num * gap) / num;
  yspac = (height - 2 * m - num * gap) / num;

  main = createGraphics(width, height);
  mainz = createGraphics(width, height);
  shape = random(1);
  
  colstyle = random(1);
  stoner = random(1);
  
  rot = random(TAU);
  rotype = random(1);
  
  disco = random(1);

  noLoop();
}

function draw() {
  background(bgC);

  main.rectMode(CENTER);
  sT = random([2,4]);
  nS = random(1);
  main.noFill();
  let off = random(abun)
  
  for (let x = 0; x <= width; x += xspac / 2 + gap) {
    for (let y = 0; y <= height; y += yspac / 2 + gap) {
      
      let n = noise(x*nf+off, y*nf+off);
      let sn = floor(n*10);
      
      if (colstyle <0.42){
      main.stroke(pal[palC][sn]);
      } else {
      main.stroke(random(pal[palC]));  
      }
      
      if (nS < 0.69){
      main.strokeWeight(sT); 
      } else {
      main.strokeWeight(n*sT);  
      }
        
      if (n < 0.69) {
        main.push();
        main.translate(x, y);

        if (rotype < 0.69) {
          main.rotate(round(n * rot));
        } else {
          main.rotate(n * rot);
        }

        if (shape <= 0.4) {
          main.rect(0, 0, xspac, yspac);
        } else if (shape <= 0.7) {
          main.ellipse(0, 0, xspac, yspac);
        } else {
          main.triangle(
            0 - xspac / 2,
            0 + yspac / 2,
            0,
            0 - yspac / 2,
            0 + xspac / 2,
            0 + yspac / 2
          );
        }
        main.pop();
      }
    }
  }

  mainz.imageMode(CENTER);

  let xx = width / 2 - 36;
  let yy = height / 2 - 30;
  
  if (stoner<0.9969){
  fnum = random([22, 34]); 
  } else {
  fnum = 420;  
  }
  
  for (let i = 0; i < fnum; i++) {
    mainz.image(main, xx, yy);

    if (disco<0.69){
    xx += 6;
    yy += 6;
    } else {
    xx += floor(random(3,12));
    yy += floor(random(3,12));
    } 
  }

  mainrot = random([0, QUARTER_PI,0,HALF_PI, HALF_PI + QUARTER_PI,HALF_PI,0,HALF_PI]);

  chipMode = random(1);
  chipz = random([0.5,0.69,0.5,0.42,0.34])

  imageMode(CENTER);
  push();
  translate(width / 2, height / 2);
  rotate(mainrot);
  image(mainz, 0, 0);
  if (chipMode > 0.69) {
    rotate(random([mainrot, mainrot * 2]));
    image(mainz, 0, 0, width * chipz, height * chipz);
  }
  pop();

  bords = random(1);

  if (bords < 0.84) {
    push();
    noFill();
    stroke(bgC);
    strokeWeight(random([200, 400, 600, 400]));
    rect(width / 2, height / 2, width, height);
    pop();
  } else if (bords < 0.89){
    push();
    noFill();
    stroke(bgC);
    strokeWeight(600);
    circle(width / 2, height / 2, width*1.15);
    pop();
  }
  
  filter(BLUR, random(4.2, 11));
  filter(POSTERIZE, random(2.42, 6.9));
  noiseImage(this, 1, 12); //texture overlay2

  fxpreview();
}

function noiseImage(img, scaleFactor, amount) {
  img.loadPixels();
  let change = amount * sqrt(scaleFactor);
  let size =
    4 * (img.width * img.pixelDensity()) * (img.height * img.pixelDensity());
  let pixels = img.pixels;
  for (let i = 0; i < size; i += 4) {
    var n = -change + random() * change * 2;
    pixels[i] += n;
    pixels[i + 1] += n;
    pixels[i + 2] += n;
  }
  img.updatePixels();
}

function preDraw() {
  let seed = floor(999999 * fxrand());
  randomSeed(seed);
  noiseSeed(seed);
  let tempcan = createCanvas(w, w);
  tempcan.parent("fulllscreen");
  rectMode(CENTER);
  pixelDensity(1);
  colorMode(HSB);
}

function mousePressed() {
  saveCanvas("HA-0", "png");
}

function keyTyped() {
  if (key === "s" || key === "S") {
    saveCanvas("HA-0", "png");
  }
}
